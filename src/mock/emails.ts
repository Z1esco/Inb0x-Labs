import type {
  EmailAnalysis,
  EmailCategory,
  EmailThreadDetail,
  PriorityLevel,
} from "@/types/contracts";

function analysis(
  summary: string,
  category: EmailCategory,
  priorityLevel: PriorityLevel,
  priorityScore: number,
  needsReply: boolean,
  options: Partial<EmailAnalysis> = {},
): EmailAnalysis {
  return {
    summary,
    category,
    priorityLevel,
    priorityScore,
    needsReply,
    replyReason: needsReply ? "A response or decision is requested." : null,
    priorityReason: `${priorityLevel} priority based on the explicit request and timing.`,
    confidence: 0.92,
    deadlines: [],
    actionItems: [],
    meetings: [],
    evidence: [],
    safetyFlags: [],
    ...options,
  };
}
function thread(
  id: string,
  subject: string,
  sender: string,
  sentAt: string,
  body: string,
  value: EmailAnalysis,
  messageCount = 1,
): EmailThreadDetail {
  return {
    id,
    subject,
    participants: [sender, "you@inb0x.demo"],
    senderNames: [sender.split("@")[0] ?? sender],
    snippet: body.slice(0, 145),
    latestMessageAt: sentAt,
    messageCount,
    hasAttachments: false,
    labels: ["INBOX"],
    analysis: value,
    contentHash: `demo-${id}`,
    normalizedCharacterCount: body.length,
    trimmed: false,
    containsPotentialPromptInjection: id === "prompt-injection",
    messages: [
      {
        id: `${id}-message-1`,
        from: sender,
        to: ["you@inb0x.demo"],
        cc: [],
        replyTo: null,
        sentAt,
        subject,
        body,
        mimeType: "text/plain",
        attachments: [],
        trimmed: false,
        containsPotentialPromptInjection: id === "prompt-injection",
      },
    ],
  };
}

